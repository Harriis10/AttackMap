def test_pick_save_bridge_handles_string_and_list(monkeypatch: pytest.MonkeyPatch) -> None:
    from attackmap.ui.launch import _Bridge
    from attackmap.ui.server import LoopbackApp

    app = LoopbackApp()
    bridge = _Bridge(app)

    class FakeWindow:
        def create_file_dialog(self, dialog_type, *, save_filename: str = ""):
            if dialog_type == 1:  # SAVE_DIALOG placeholder
                return r"C:\Reports\attackmap-report.md"
            return None

    class FakeWebview:
        SAVE_DIALOG = 1
        windows = [FakeWindow()]

    monkeypatch.setitem(sys.modules, "webview", FakeWebview)
    assert bridge.pick_save("attackmap-test.md", ".md") == r"C:\Reports\attackmap-report.md"

    class FakeWindowList:
        def create_file_dialog(self, dialog_type, *, save_filename: str = ""):
            return [r"C:\Reports\attackmap-list.md"]

    FakeWebview.windows = [FakeWindowList()]
    assert bridge.pick_save("attackmap-test.md", ".md") == r"C:\Reports\attackmap-list.md"


