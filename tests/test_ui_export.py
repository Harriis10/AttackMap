@pytest.mark.skipif(sys.platform != "win32", reason="O_NOFOLLOW test is Windows-specific")
def test_export_endpoint_writes_markdown(tmp_path: Path) -> None:
    from attackmap.ui.server import LoopbackApp, make_server

    data = json.loads(FIX.read_text(encoding="utf-8"))
    app = LoopbackApp(report=decode_report(data, repo_name="juice-shop"))
    server = make_server(app, start=True)
    token = app.token
    try:
        out = tmp_path / "exports"
        out.mkdir()
        dest = out / "attackmap-juice-findings.md"
        req_body = json.dumps({"view": "findings", "path": str(dest)}).encode("utf-8")
        req = Request(
            f"http://127.0.0.1:{server.server_address[1]}/api/export",
            data=req_body,
            headers={"Content-Type": "application/json", "X-AttackMap-Token": token},
            method="POST",
        )
        with urlopen(req, timeout=5) as resp:
            result = json.loads(resp.read().decode("utf-8"))
        assert result.get("ok") is True
        assert dest.is_file()
        assert "# Findings" in dest.read_text(encoding="utf-8")
    finally:
        server.shutdown()


