"""Render a GUI tab as Markdown for export."""

from __future__ import annotations

from typing import Any

SUPPORTED_SUFFIXES = {".md", ".pdf"}

_VIEW_TITLES = {
    "overview": "Overview",
    "findings": "Findings",
    "exploitability": "Exploitability",
    "paths": "Attack paths",
    "surface": "Attack surface",
    "diagrams": "Diagrams",
    "review": "Review",
    "ai-review": "AI Review",
    "diff": "Diff",
    "fleet": "Fleet",
    "deps": "Dependencies",
    "secrets": "Secrets",
    "ci": "CI workflows",
    "flows": "Data flows",
    "analyzers": "Analyzers",
    "recents": "Recent scans",
}


def suggested_export_name(repo_name: str, view: str, suffix: str) -> str:
    """Return a clean default file name for a tab export."""
    safe = "".join(c if c.isalnum() or c in "-_" else "-" for c in repo_name).strip("-").lower()
    if not safe:
        safe = "report"
    return f"attackmap-{safe}-{view}{suffix}"


def _cell(text: str | int | float | None) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ") if text is not None else ""


def _table(headers: list[str], rows: list[list[Any]]) -> str:
    if not rows:
        return ""
    out = ["| " + " | ".join(_cell(h) for h in headers) + " |"]
    out.append("| " + " | ".join("---" for _ in headers) + " |")
    for row in rows:
        cells = [_cell(c) for c in row]
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def _heading(level: int, text: str) -> str:
    return f"{'#' * level} {text}"


def _wrap(view: str, repo_name: str, body: str) -> str:
    title = _VIEW_TITLES.get(view, view)
    lines = [
        f"# {title}",
        "",
        f"Repository: `{repo_name}`",
        "",
        "Generated by AttackMap.",
        "",
        "---",
        "",
        body,
    ]
    return "\n".join(lines)


def _render_findings(report: dict[str, Any]) -> str:
    findings = report.get("findings") or []
    if not findings:
        return "No findings."
    lines: list[str] = []
    for f in findings:
        sev = f.get("severity") or "info"
        lines.append(f"## {f.get('title', 'Finding')}")
        lines.append("")
        lines.append(f"- **Severity:** {sev}")
        locs = f.get("locations") or []
        if locs:
            lines.append(f"- **Location:** {locs[0].get('file', '')}:{locs[0].get('line', '')}".rstrip(":"))
        lines.append("")
        if f.get("evidence"):
            lines.append("**Evidence**")
            lines.append("")
            for e in f.get("evidence"):
                lines.append(f"- {e}")
            lines.append("")
        if f.get("mitigation"):
            lines.append(f"**Remediation:** {f.get('mitigation')}")
            lines.append("")
        techniques = (f.get("attack_techniques") or []) or []
        ids = [
            (t if isinstance(t, str) else (t.get("technique_id") or t.get("id") or ""))
            for t in techniques
        ]
        ids = [i for i in ids if i]
        if ids:
            lines.append(f"**ATT&CK:** {', '.join(ids)}")
            lines.append("")
    suppressed = report.get("suppressed") or []
    if suppressed:
        lines.append("## Suppressed findings")
        lines.append("")
        for s in suppressed:
            lines.append(f"- {s.get('title') or s.get('id')} — {s.get('reason') or ''}")
        lines.append("")
    return "\n".join(lines)


def _render_exploitability(report: dict[str, Any]) -> str:
    rows = report.get("exploitability") or []
    if not rows:
        return "No route→sink exploitability paths."
    lines: list[str] = []
    for r in rows:
        lines.append(f"## {r.get('subject') or r.get('route')}")
        lines.append("")
        lines.append(f"- **Method:** {r.get('method', '')} {r.get('route', '')}")
        lines.append(f"- **Sink:** {r.get('sinkKind', '')}")
        lines.append(f"- **Score:** {r.get('score', '')} ({r.get('tier', '')})")
        lines.append(f"- **Location:** {r.get('location', '')}")
        lines.append("")
        factors = r.get("factors") or []
        if factors:
            lines.append("**Factors**")
            lines.append("")
            for f in factors:
                lines.append(f"- {f.get('points', '')} {f.get('name', '')}{' — ' + f.get('detail', '') if f.get('detail') else ''}")
            lines.append("")
    return "\n".join(lines)


def _render_paths(report: dict[str, Any]) -> str:
    paths = report.get("attackPaths") or []
    if not paths:
        return "No attack paths."
    lines: list[str] = []
    for p in paths:
        lines.append(f"## {p.get('name', 'Attack path')}")
        lines.append("")
        steps = p.get("steps") or []
        rendered = []
        for s in steps:
            if isinstance(s, str):
                rendered.append(s)
            else:
                rendered.append(
                    (s.get("stage") or "")
                    + (
                        ": " + (s.get("detail") or s.get("action") or s.get("label") or "")
                        if s.get("detail") or s.get("action") or s.get("label")
                        else ""
                    )
                )
        rendered = [r for r in rendered if r]
        lines.append(" → ".join(rendered))
        lines.append("")
        if p.get("impact"):
            lines.append(f"**Impact:** {p.get('impact')}")
            lines.append("")
    return "\n".join(lines)


def _render_surface(report: dict[str, Any]) -> str:
    surfaces = report.get("attackSurfaces") or []
    if not surfaces:
        return "No attack surface."
    rows = [
        [s.get("method", ""), s.get("route") or s.get("path", ""), s.get("category", ""), s.get("exposure", ""), s.get("file", "")]
        for s in surfaces
    ]
    return _table(["Method", "Path", "Category", "Exposure", "File"], rows)


def _render_diagrams(report: dict[str, Any]) -> str:
    diagrams = report.get("diagrams") or {}
    paths = diagrams.get("paths") or ""
    topology = diagrams.get("topology") or ""
    if not paths and not topology:
        return "No diagrams."
    lines: list[str] = []
    if paths:
        lines.append("## Paths")
        lines.append("")
        lines.append("```mermaid")
        lines.append(paths)
        lines.append("```")
        lines.append("")
    if topology:
        lines.append("## Topology")
        lines.append("")
        lines.append("```mermaid")
        lines.append(topology)
        lines.append("```")
        lines.append("")
    return "\n".join(lines)


def _render_dependencies(report: dict[str, Any]) -> str:
    deps = report.get("dependencies") or []
    vulns = report.get("vulnerabilities") or []
    lines: list[str] = []
    if deps:
        rows = [
            [d.get("name"), d.get("version"), d.get("ecosystem"), "direct" if d.get("direct") else "transitive", d.get("via") or d.get("file")]
            for d in deps
        ]
        lines.append("## Dependencies")
        lines.append("")
        lines.append(_table(["Package", "Version", "Ecosystem", "Scope", "Resolved via"], rows))
        lines.append("")
    else:
        lines.append("No dependencies detected.")
        lines.append("")
    if vulns:
        rows = [
            [v.get("id") or v.get("osv_id"), ", ".join(v.get("aliases") or []), v.get("summary"), v.get("affected") or v.get("package")]
            for v in vulns
        ]
        lines.append("## Known advisories")
        lines.append("")
        lines.append(_table(["ID", "Aliases", "Summary", "Affected"], rows))
        lines.append("")
    return "\n".join(lines)


def _render_inventory(items: list[dict[str, Any]], empty: str, title: str | None = None) -> str:
    if not items:
        return empty
    lines: list[str] = []
    if title:
        lines.append(f"## {title}")
        lines.append("")
    rows: list[list[Any]] = []
    for item in items:
        title_text = (
            item.get("name")
            or item.get("id")
            or item.get("kind")
            or item.get("rule")
            or item.get("label")
            or item.get("package")
            or (
                f"{item.get('route_method', '')} {item.get('route_path', '')} → {item.get('sink_kind', '')}".strip()
            )
            or "item"
        )
        loc = (
            item.get("location")
            or (
                f"{item.get('file', '')}:{item.get('line', '')}".rstrip(":")
                if item.get("file")
                else ""
            )
            or (
                f"{item.get('sink_file', '')}:{item.get('sink_line', '')}".rstrip(":")
                if item.get("sink_file")
                else ""
            )
        )
        rows.append([title_text, item.get("summary") or item.get("message") or item.get("ecosystem") or "", loc])
    lines.append(_table(["Item", "Summary", "Location"], rows))
    lines.append("")
    return "\n".join(lines)


def _render_fleet(report: dict[str, Any]) -> str:
    fleet = report.get("fleet")
    if not fleet:
        return "Select two or more folders with + Fleet, then run a scan."
    lines: list[str] = []
    lines.append(f"- **Repos:** {fleet.get('repo_count', 0)}")
    lines.append(f"- **Findings:** {fleet.get('total_findings', 0)}")
    lines.append("")
    repos = fleet.get("repos") or []
    if repos:
        lines.append("## Per-repo rollup")
        lines.append("")
        for r in repos:
            lines.append(f"- {r.get('repo_id') or r.get('root')} — {r.get('findings')} findings")
        lines.append("")
    links = fleet.get("cross_repo_links") or []
    if links:
        lines.append("## Contract links")
        lines.append("")
        for item in links:
            lines.append(f"- {item.get('client_repo')} → {item.get('server_repo')}: {item.get('method', '')} {item.get('path_template', '')}")
        lines.append("")
    failed = fleet.get("failed") or []
    if failed:
        lines.append("## Failed")
        lines.append("")
        for f in failed:
            lines.append(f"- {f.get('repo_id')}: {f.get('error')}")
        lines.append("")
    gaps = (fleet.get("trust_gaps") or []) + (fleet.get("cross_boundary_flows") or [])
    if gaps:
        lines.append("## Trust gaps / cross-boundary")
        lines.append("")
        for g in gaps:
            lines.append(f"- {g.get('client_repo')} → {g.get('server_repo')}: {g.get('basis') or g.get('kind')}")
        lines.append("")
    return "\n".join(lines)


def _render_analyzers(report: dict[str, Any]) -> str:
    errors = report.get("analyzerErrors") or []
    limits = report.get("limitations") or []
    if not errors and not limits:
        return "Analyzers completed without recorded errors."
    lines: list[str] = []
    if errors:
        lines.append("## Errors")
        lines.append("")
        for e in errors:
            lines.append(f"- **{e.get('analyzer', '')}:** {e.get('message', '')}")
        lines.append("")
    if limits:
        lines.append("## Limitations")
        lines.append("")
        for item in limits:
            lines.append(f"- {item}")
        lines.append("")
    return "\n".join(lines)


def _render_recents(recents: list[dict[str, Any]] | None) -> str:
    items = recents or []
    if not items:
        return "No recent scans."
    lines = [f"- {r.get('name')} — `{r.get('path')}`" for r in items]
    return "\n".join(lines) + "\n"


def _render_overview(report: dict[str, Any]) -> str:
    lines: list[str] = []
    counts = report.get("severityCounts") or {}
    lines.append(f"- **Findings:** {report.get('findingCount', 0)}")
    for sev in ("high", "medium", "low", "info"):
        if sev in counts:
            lines.append(f"- **{sev.capitalize()}:** {counts[sev]}")
    lines.append("")
    top = report.get("topPath")
    if top:
        lines.append("## Most exploitable path")
        lines.append("")
        lines.append(f"- {top.get('method', '')} {top.get('route') or top.get('subject')} — score {top.get('score', '')}")
        lines.append("")
    arch = (report.get("diagrams") or {}).get("architecture")
    if arch:
        lines.append("## Architecture summary")
        lines.append("")
        lines.append(arch)
        lines.append("")
    return "\n".join(lines)


def render_view_markdown(
    view: str,
    report: dict[str, Any],
    *,
    repo_name: str,
    recents: list[dict[str, Any]] | None = None,
) -> str:
    """Return a Markdown string for the selected tab."""
    if view not in _VIEW_TITLES:
        raise ValueError(f"unknown view: {view}")
    if view == "settings":
        raise ValueError("settings tab cannot be exported")

    body = ""
    if view == "overview":
        body = _render_overview(report)
    elif view == "findings":
        body = _render_findings(report)
    elif view == "exploitability":
        body = _render_exploitability(report)
    elif view == "paths":
        body = _render_paths(report)
    elif view == "surface":
        body = _render_surface(report)
    elif view == "diagrams":
        body = _render_diagrams(report)
    elif view == "review":
        body = report.get("reviewMd") or "No review yet."
    elif view == "ai-review":
        ai_md = report.get("aiReviewMd")
        if ai_md:
            body = ai_md
        elif report.get("aiReviewRequested"):
            body = "AI Review was requested but produced no output. Check the *.meta.json files in the report folder for backend details."
        else:
            body = "AI Review is generated only when an LLM mode (review / hunt / remediate / triage) is enabled for a scan. Heuristic-only runs never send code off this machine."
    elif view == "diff":
        body = report.get("diffMd") or "No baseline diff. Re-run the same repo to compare."
    elif view == "fleet":
        body = _render_fleet(report)
    elif view == "deps":
        body = _render_dependencies(report)
    elif view == "secrets":
        body = _render_inventory(report.get("secrets") or [], "No secrets.")
    elif view == "ci":
        body = _render_inventory(report.get("workflows") or [], "No CI workflow issues.")
    elif view == "flows":
        body = _render_inventory(report.get("dataFlows") or [], "No data-flow chains.")
    elif view == "analyzers":
        body = _render_analyzers(report)
    elif view == "recents":
        body = _render_recents(recents)

    return _wrap(view, repo_name, body)
